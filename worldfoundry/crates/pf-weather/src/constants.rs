//! Every constant WEATHER-V0 and COLDPOOL-1 read, with unit and source.
//!
//! Source classes (same vocabulary as the climate tiers, ADR 039 C5):
//! - `cited` : a relation or number read in a fetched source by the
//!   design review-MECHANICS consultant on 2026-10-21 (tag [V] in
//!   `unpublished-design-record review-mechanics/REPORT.md`); this lane did not re-fetch.
//! - `recalled` : a textbook/standard value recalled by this lane, not checked
//!   tonight.
//! - `project_assumption` : a modelling choice of this lane (often a
//!   calibration), awaiting review.
//! - `world` : read from the world's own artifacts at run time (overrides the
//!   default value printed here).

use serde::Serialize;

#[derive(Debug, Clone, Serialize)]
pub struct ConstantRow {
    pub name: &'static str,
    pub value: f64,
    pub unit: &'static str,
    pub class: &'static str,
    pub basis: &'static str,
}

