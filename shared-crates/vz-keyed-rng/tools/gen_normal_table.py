#!/usr/bin/env python3
"""Generate src/normal_table.rs for vz.keyed-rng/v1 `normal_q32_table_v1`.

The emitted integer constants ARE the specification: the library never
recomputes them, so draws stay bit-stable on every platform. This script is
kept only so the table's origin is reproducible and reviewable.

Q32 means value * 2^32 rounded to the nearest integer.

COARSE[k-1] = Phi^-1(k / 4096) for k = 1..=4095 (central bin edges); made
exactly antisymmetric by computing the lower half and mirroring, with
COARSE[2047] (k = 2048) = 0.

TAIL[s] = Phi^-1(s / 2^24) for s = 1..=4096, so TAIL[4096] == COARSE[0].
TAIL[0] is the declared clamp Phi^-1(2^-25) (half the first sub-bin's
probability): the distribution is truncated at about -5.42 sigma, and the
upper tail is the mirror image.

Phi^-1 is Python's statistics.NormalDist.inv_cdf (Wichura AS241, double
precision). Usage: python3 -I tools/gen_normal_table.py > src/normal_table.rs
"""
from statistics import NormalDist

ND = NormalDist()
Q = 2 ** 32


def q32(p):
    return int(round(ND.inv_cdf(p) * Q))


def main():
    lower = [q32(k / 4096) for k in range(1, 2048)]  # k = 1..=2047
    coarse = lower + [0] + [-v for v in reversed(lower)]  # k = 1..=4095
    assert len(coarse) == 4095
    tail = [q32(2.0 ** -25)] + [q32(s / 2 ** 24) for s in range(1, 4097)]
    assert len(tail) == 4097 and tail[4096] == coarse[0]
    out = []
    out.append("// GENERATED by tools/gen_normal_table.py. Do not edit by hand.")
    out.append("// vz.keyed-rng/v1 normal_q32_table_v1: Q32 standard-normal quantiles.")
    out.append("// COARSE[k-1] = Phi^-1(k/4096), k = 1..=4095 (antisymmetric).")
    out.append("// TAIL[s] = Phi^-1(s/2^24), s = 1..=4096; TAIL[0] = Phi^-1(2^-25) (declared clamp).")
    out.append("")
    for name, vals in (("COARSE", coarse), ("TAIL", tail)):
        out.append(f"pub(crate) static {name}: [i64; {len(vals)}] = [")
        for i in range(0, len(vals), 6):
            out.append("    " + ", ".join(str(v) for v in vals[i:i + 6]) + ",")
        out.append("];")
        out.append("")
    print("\n".join(out), end="")


if __name__ == "__main__":
    main()
